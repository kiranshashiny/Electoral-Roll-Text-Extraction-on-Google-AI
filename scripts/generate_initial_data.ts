// Convert to elector records format
export interface FinalRecord {
  "Dataset": string;
  "Serial Number": number;
  "Voter ID": string;
  "Name": string;
  "Relation": string;
  "address": string;
  "Age": number;
  "Gender": string;
}

export function toCsvRows(records: FinalRecord[]): string {
  const headers = ["Dataset", "Serial Number", "Voter ID", "Name", "Relation", "address", "Age", "Gender"];
  const lines = [headers.join(",")];
  for (const r of records) {
    const esc = (val: any) => {
      const s = String(val ?? "").trim();
      if (s.includes(",") || s.includes('"') || s.includes("\n")) {
        return `"${s.replace(/"/g, '""')}"`;
      }
      return s;
    };
    lines.push([
      esc(r["Dataset"]),
      r["Serial Number"],
      esc(r["Voter ID"]),
      esc(r["Name"]),
      esc(r["Relation"]),
      esc(r["address"]),
      r["Age"],
      esc(r["Gender"])
    ].join(","));
  }
  return lines.join("\n");
}

